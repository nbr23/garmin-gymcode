#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/source/BuildConfig.mc"
ENV_FILE="$ROOT/.env"

from_env_file() {
    [[ -f "$ENV_FILE" ]] || return 0
    { grep -E "^$1=" "$ENV_FILE" || true; } | tail -1 | cut -d= -f2-
}

die() {
    printf 'ERROR: %s\n' "$1" >&2
    shift
    [[ $# -eq 0 ]] || printf '%s\n' "$@" >&2
    exit 1
}

escape() { printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'; }

MEMBERSHIPS="${MEMBERSHIPS:-$(from_env_file MEMBERSHIPS)}"

membership_entries() {
    local IFS=';' entry name code
    for entry in $MEMBERSHIPS; do
        [[ -n "$entry" ]] || continue
        [[ "$entry" == *:* ]] || die "membership '$entry' is not in Name:code form"
        name="${entry%%:*}"
        code="${entry#*:}"
        # Code39 only carries digit patterns; anything else crashes the encoder on the watch
        [[ "$code" =~ ^[0-9]+$ ]] || die "membership '$name' has code '$code'; only digits are supported"
        printf '        ["%s", "%s"],\n' "$(escape "$name")" "$code"
    done
}

ENTRIES="$(membership_entries)"
ENTRIES="${ENTRIES%,}"

cat > "$OUT" << EOF
// Generated by scripts/gen-config.sh from .env at build time. Do not edit.
module BuildConfig {
    const MEMBERSHIPS = [
$ENTRIES
    ];
}
EOF

echo "Generated $OUT"
